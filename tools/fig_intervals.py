"""Figure: item-level vs two-level intervals, with the per-seed estimates overlaid.

The point of the figure is that the per-seed estimates spill outside the
item-level interval -- i.e. the conventional interval is narrower than the
variation of the quantity it is an interval for. Encoding is by position,
line weight and grey level rather than hue, so the figure survives grayscale
printing, which is the common case for this venue.

Data comes from .aris/figdata_intervals.json, generated by running
tools/seed_scene_ci.py itself, so the figure cannot drift from the tables.
"""
import json
import os
import sys

import numpy as np
if not hasattr(np, 'Inf'):          # this matplotlib predates the NumPy 2.0 removal
    np.Inf, np.NINF = np.inf, -np.inf

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(HERE, 'paper', 'pr', '.aris', 'figdata_intervals.json')

INK, MID, LIGHT = '#1a1a1a', '#6e6e6e', '#b4b4b4'

# Validated categorical palette (dataviz reference instance, light mode):
# slot1 blue #2a78d6, slot2 orange #eb6834, slot3 aqua #1baf7a, slot4 yellow #eda100.
# Checked with scripts/validate_palette.js: lightness band, chroma floor, CVD
# separation (worst adjacent dE 9.1 protan) and normal-vision floor all pass; the
# contrast warning is discharged by axis labels, legends and the matching tables.
# Hues are assigned to entities in fixed order and never cycled; every figure also
# carries a non-colour encoding (marker, hatch, line style) so identity never
# depends on colour alone.
C_BASE, C_ADD, C_GATE, C_EVID = '#2a78d6', '#eb6834', '#1baf7a', '#eda100'


plt.rcParams.update({
    'font.family': 'serif',
    'font.serif': ['Nimbus Roman', 'Times New Roman', 'DejaVu Serif'],
    'font.size': 9,
    'axes.linewidth': 0.6,
    'xtick.major.width': 0.6,
    'pdf.fonttype': 42,
})


def main():
    rows = json.load(open(DATA))
    fig, ax = plt.subplots(figsize=(6.0, 3.5))

    # one slot per contrast, grouped by dataset with a gap between groups
    ys, labels, group_at = [], [], {}
    y = 0.0
    for i, r in enumerate(rows):
        if i and r['dataset'] != rows[i - 1]['dataset']:
            y += 0.9
        group_at.setdefault(r['dataset'], []).append(y)
        ys.append(y)
        labels.append(r['arm'])
        y += 1.0

    ax.axvline(0, color=LIGHT, lw=0.8, zorder=0)

    OFF = 0.17
    HUE = {'Additive': C_ADD, 'Gated': C_GATE, 'Evidence': C_EVID}
    for r, yy in zip(rows, ys):
        col = HUE[r['arm']]
        # item-only: the conventional interval, recessive
        lo, hi = r['item']
        ax.plot([lo, hi], [yy + OFF] * 2, color=col, alpha=.55, lw=1.3, solid_capstyle='butt', zorder=2)
        for x in (lo, hi):
            ax.plot([x, x], [yy + OFF - 0.07, yy + OFF + 0.07], color=col, alpha=.55, lw=1.3, zorder=2)
        # two-level: the calibrated interval, dominant
        lo2, hi2 = r['two']
        ax.plot([lo2, hi2], [yy - OFF] * 2, color=col, lw=2.4, solid_capstyle='butt', zorder=3)
        for x in (lo2, hi2):
            ax.plot([x, x], [yy - OFF - 0.10, yy - OFF + 0.10], color=col, lw=2.4, zorder=3)
        # per-seed estimates: what the quantity actually did across retrainings
        ax.plot(r['seeds'], [yy] * len(r['seeds']), 'o', ms=5.0,
                mfc='white', mec=INK, mew=0.9, zorder=4)
        # the seed-averaged point estimate
        ax.plot([r['d']], [yy], 'D', ms=4.8, mfc=col, mec=INK, mew=0.9, zorder=5)

    ax.set_yticks(ys)
    ax.set_yticklabels(labels)
    ax.invert_yaxis()
    ax.set_xlabel(r'$\Delta$ Success vs. implicit baseline')
    ax.set_xlim(-11.2, 9.2)
    for side in ('top', 'right', 'left'):
        ax.spines[side].set_visible(False)
    ax.tick_params(axis='y', length=0)
    ax.grid(axis='x', color=LIGHT, lw=0.4, alpha=0.6, zorder=0)
    ax.set_axisbelow(True)

    # dataset group labels, placed outside the plotting area
    for ds, yy in group_at.items():
        ax.text(-0.155, sum(yy) / len(yy), ds, transform=ax.get_yaxis_transform(),
                rotation=90, va='center', ha='center', fontsize=9, color=INK)

    # one annotation only, on the row that makes the point most sharply
    g = [r for r in rows if r['dataset'] == 'nuScenes' and r['arm'] == 'Gated'][0]
    gy = ys[rows.index(g)]
    # aligned to its row rather than led by an arrow: a leader from the interval
    # to clear space would have to cross that row's own seed markers.
    ax.text(4.9, gy, 'item-level width 1.0,\nseed spread 11.7',
            fontsize=7.5, color=INK, ha='left', va='center')

    handles = [
        Line2D([], [], color=MID, lw=1.2, label='Item-level 95% CI (conventional)'),
        Line2D([], [], color=INK, lw=2.0, label='Two-level 95% CI (seed x cluster)'),
        Line2D([], [], marker='o', ls='none', mfc='white', mec=INK, mew=1.0, ms=5.0,
               label='Per-seed estimate'),
        Line2D([], [], marker='D', ls='none', mfc='#9a9a9a', mec=INK, mew=1.0, ms=4.8, label='Seed-averaged estimate'),
    ]
    ax.legend(handles=handles, loc='lower left', bbox_to_anchor=(0.0, -0.40),
              ncol=2, frameon=False, fontsize=7.5, handlelength=2.2,
              columnspacing=1.6, borderaxespad=0.0)

    fig.tight_layout()
    for ext in ('pdf', 'png'):
        out = os.path.join(HERE, 'paper', 'pr', 'figures', f'intervals.{ext}')
        fig.savefig(out, bbox_inches='tight', dpi=200)
        print('wrote', out)


if __name__ == '__main__':
    main()
